"""Generate the colour tokens for the web studio and the Android app.

    python scripts/build_tokens.py          # write the generated files
    python scripts/build_tokens.py --check  # CI: fail if stale or below contrast

Source: design/tokens.json (light and dark palettes plus the contrast pairs
that must hold in both). Outputs:

    webapp/frontend/src/styles/palette.generated.css   CSS custom properties;
        dark mode follows prefers-color-scheme unless <html data-theme> says
        otherwise
    mobile/lib/theme_tokens.dart                        ThemeTokens.light/.dark

Every pair in "contrast" is checked with the WCAG 2.x relative-luminance
formula in both palettes; a failure stops the build.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "tokens.json"
CSS_OUT = ROOT / "webapp" / "frontend" / "src" / "styles" / "palette.generated.css"
DART_OUT = ROOT / "mobile" / "lib" / "theme_tokens.dart"
HEADER = "GENERATED by scripts/build_tokens.py from design/tokens.json. Do not edit."


def luminance(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    channels = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
              for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(a: str, b: str) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def check_contrast(tokens: dict) -> list[str]:
    failures = []
    for theme, palette in tokens["palettes"].items():
        for fg, bg, minimum, why in tokens["contrast"]["pairs"]:
            ratio = contrast(palette[fg], palette[bg])
            if ratio < minimum:
                failures.append(f"{theme}: {fg} on {bg} is {ratio:.2f}:1, "
                                f"needs {minimum}:1 ({why})")
    return failures


def css(tokens: dict) -> str:
    def block(palette: dict, indent: str) -> str:
        return "\n".join(f"{indent}--{name}: {value};" for name, value in palette.items())

    light, dark = tokens["palettes"]["light"], tokens["palettes"]["dark"]
    return (
        f"/* {HEADER} */\n\n"
        ":root {\n"
        "  color-scheme: light;\n"
        f"{block(light, '  ')}\n"
        "}\n\n"
        "@media (prefers-color-scheme: dark) {\n"
        '  :root:not([data-theme="light"]) {\n'
        "    color-scheme: dark;\n"
        f"{block(dark, '    ')}\n"
        "  }\n"
        "}\n\n"
        ':root[data-theme="dark"] {\n'
        "  color-scheme: dark;\n"
        f"{block(dark, '  ')}\n"
        "}\n"
    )


def dart_name(token: str) -> str:
    head, *rest = token.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def dart(tokens: dict) -> str:
    names = list(tokens["palettes"]["light"])

    def instance(palette: dict) -> str:
        fields = "\n".join(
            f"    {dart_name(n)}: Color(0xff{palette[n].lstrip('#').lower()}),"
            for n in names)
        return f"ThemeTokens._(\n{fields}\n  )"

    fields = "\n".join(f"  final Color {dart_name(n)};" for n in names)
    params = "\n".join(f"    required this.{dart_name(n)}," for n in names)
    return (
        f"// {HEADER}\n"
        "import 'dart:ui';\n\n"
        "/// Shared VeriScript palette (same values as the web studio).\n"
        "class ThemeTokens {\n"
        f"  const ThemeTokens._({{\n{params}\n  }});\n\n"
        f"{fields}\n\n"
        "  /// Paper & Ink.\n"
        f"  static const light = {instance(tokens['palettes']['light'])};\n\n"
        "  /// Night Studio.\n"
        f"  static const dark = {instance(tokens['palettes']['dark'])};\n"
        "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="verify contrast and that generated files are current")
    args = parser.parse_args()

    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    light, dark = tokens["palettes"]["light"], tokens["palettes"]["dark"]
    if set(light) != set(dark):
        print(f"palettes differ in names: {sorted(set(light) ^ set(dark))}")
        return 1
    failures = check_contrast(tokens)
    for failure in failures:
        print("contrast:", failure)

    outputs = {CSS_OUT: css(tokens), DART_OUT: dart(tokens)}
    stale = [p for p, text in outputs.items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run scripts/build_tokens.py)")
        return 1 if failures or stale else 0
    if failures:
        return 1
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
